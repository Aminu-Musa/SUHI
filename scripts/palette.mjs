import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { buildRamp, RAMPS } from './lib/ramps.mjs';
import { THEME_TOKENS } from './lib/tokens.mjs';

const THEMES = ['nocturne', 'modernist'];

/** Render the generated ramp stylesheet: --hot-1..5, --cold-1..5, --neutral-mid per theme. */
export function renderRampsCss() {
  const blocks = THEMES.map((theme) => {
    const decls = [];
    for (const family of ['hot', 'cold']) {
      buildRamp(RAMPS[theme][family]).forEach((hex, i) =>
        decls.push(`  --${family}-${i + 1}: ${hex};`));
    }
    decls.push(`  --neutral-mid: ${THEME_TOKENS[theme]['--neutral-mid']};`);
    return `html[data-theme="${theme}"] {\n${decls.join('\n')}\n}\n`;
  });
  return `/* GENERATED by \`npm run palette\` (scripts/palette.mjs). Do not edit by hand. */\n\n${blocks.join('\n')}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = new URL('../src/styles/_ramps.css', import.meta.url);
  writeFileSync(out, renderRampsCss());
  console.log(`wrote ${fileURLToPath(out)}`);
}
